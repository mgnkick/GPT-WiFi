export function getRandomAuditTips(count: number = 2, excludeIds: string[] = []): RandomAuditTip[] {
  const available = RANDOM_AUDIT_TIPS.filter(t => !excludeIds.includes(t.id));
  const pool = available.length >= count ? available : [...RANDOM_AUDIT_TIPS];
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, count);
}
